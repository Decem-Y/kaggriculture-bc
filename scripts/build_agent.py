"""Build a self-contained submission directory: main.py (common.py + npmodel.py + policy.py + agent entry point),
weights.npz and vocab.json.

  python scripts/build_agent.py runs/specialize/best.pt agents/final --team "<TEAM>" --date 41 --topk 8
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
sys.path.insert(0, SRC)

HEAD = '''# Entity Transformer behaviour-cloning agent. Generated by scripts/build_agent.py; edit src/ instead.
import os as _os, time as _time
'''

TAIL = '''

def _here():
    return None


_ROOT = _os.path.dirname(_os.path.abspath(_here.__code__.co_filename))
if not _os.path.isfile(_os.path.join(_ROOT, "weights.npz")):
    _ROOT = "/kaggle_simulations/agent"
_POLICY = None
_PASS = {"farmer": ["PASS"], "hands": [], "market": []}
AGENT_STATS = {"errors": 0, "last_error": None, "max_call": 0.0}


def agent(obs, config=None):
    global _POLICY
    t0 = _time.monotonic()
    try:
        if _POLICY is None:
            _POLICY = BCPolicy(_ROOT, team=%(team)r, won=%(won)d, date=%(date)d, topk=%(topk)d, rules=%(rules)r)
        act = _POLICY.act(obs)
    except BaseException as e:  # noqa: BLE001  an uncaught exception ends the episode for us; play PASS instead
        AGENT_STATS["errors"] += 1
        AGENT_STATS["last_error"] = repr(e)[:300]
        act = _PASS
    AGENT_STATS["max_call"] = max(AGENT_STATS["max_call"], _time.monotonic() - t0)
    return act
'''


def strip_local_imports(src):
    out = []
    skip = False
    for line in src.splitlines():
        if skip:
            if ")" in line:
                skip = False
            continue
        if re.match(r"^from (common|npmodel) import", line):
            if "(" in line and ")" not in line:
                skip = True
            continue
        out.append(line)
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ckpt", help="checkpoint .pt from train.py")
    ap.add_argument("out")
    ap.add_argument("--team", required=True, help="team to imitate (must be in the checkpoint's vocabulary)")
    ap.add_argument("--won", type=int, default=1)
    ap.add_argument("--date", type=int, required=True, help="date bucket to condition on")
    ap.add_argument("--topk", type=int, default=8)
    ap.add_argument("--no-rules", action="store_true", help="plain model, without the two goods-recovery rules")
    a = ap.parse_args()
    from export import export
    ck = export(a.ckpt, a.out)
    assert a.team in ck["vocab"], f"{a.team!r} not in vocabulary {ck['vocab']}"
    ndate = ck["cfg"]["model"].get("ndate", 0)
    assert 0 <= a.date < ndate, f"date bucket {a.date} outside [0, {ndate})"
    body = [HEAD]
    for f in ("common.py", "npmodel.py", "policy.py"):
        body.append(f"# ==== {f} ====\n" + strip_local_imports(open(os.path.join(SRC, f)).read()))
    body.append(TAIL % dict(team=a.team, won=a.won, date=a.date, topk=a.topk, rules=not a.no_rules))
    open(os.path.join(a.out, "main.py"), "w").write("\n".join(body))
    print(f"built {a.out} from {a.ckpt} (step {ck['step']}): team={a.team!r} won={a.won} date={a.date} topk={a.topk}")


if __name__ == "__main__":
    main()
